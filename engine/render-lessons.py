#!/usr/bin/env python3
"""Render the lessons ledger into CLAUDE.md blocks and the just-in-time manifest.

Two outputs, from the same set of live lessons (status active, not superseded,
not graduated, not stale; see lessonlib.live):

1. A compact block in each target CLAUDE.md: one line per lesson WITHOUT a `match:`
   field, ranked severity > hits > recency and cut at `inject_token_budget`. Lessons
   with a matcher are left out on purpose: lesson-hook.py injects them right before
   the tool call they guard, which is where they help and the only place they cost.
2. meta/lessons-manifest.json: every live lesson with a matcher (severities in
   `jit_severities`), with its target directories, for lesson-hook.py.

Default is a dry run (writes meta/lessons-injection-preview.md). --apply writes.
Only writes CLAUDE.md files that already exist. The block holds no date, so it is
byte-identical while the lessons are unchanged and stays in the prompt cache.
"""
import argparse
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import lessonlib as L  # noqa: E402

BEGIN = f"<!-- BRAIN-LESSONS:{L.NAME} BEGIN (auto-generated by brain sync; edits between markers are overwritten) -->"
END = f"<!-- BRAIN-LESSONS:{L.NAME} END -->"
PREVIEW = L.VAULT / "meta" / "lessons-injection-preview.md"


def render_block(lessons, budget_tokens):
    head = [
        BEGIN,
        "## Lessons: do not repeat these (auto-generated; do not edit between markers)",
        f"_From `{L.VAULT.name}/wiki/lessons.md`. More lessons fire just in time before matching tool calls; "
        "full history: `brain_search(\"L###\")`._",
        "",
    ]
    lines, used, dropped = [], sum(len(x) + 1 for x in head), 0
    budget_chars = budget_tokens * 4
    for l in sorted(lessons, key=L.rank_key):
        line = f"- **{l['id']}** [{l['severity']}] {L.one_line(l)}"
        if used + len(line) + 1 > budget_chars:
            dropped += 1
            continue
        lines.append(line)
        used += len(line) + 1
    tail = [f"- _{dropped} more lesson(s) over the {budget_tokens}-token budget: search-only._"] if dropped else []
    return "\n".join(head + lines + tail + [END]) + "\n", len(lines), dropped


def strip_block(text, begin, end):
    return re.sub(re.escape(begin) + r".*?" + re.escape(end) + r"\n?", "", text, flags=re.S)


def upsert(path, block, legacy):
    old = path.read_text()
    new = old
    for lb, le in legacy:  # remove blocks written by an older renderer under different markers
        new = strip_block(new, lb, le)
    if BEGIN in new and END in new:
        new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda _: block, new, flags=re.S)
    else:
        new = new.rstrip("\n") + ("\n\n" if new.strip() else "") + block
    return old, new


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    if not L.LESSONS.exists():
        print(f"no lessons file at {L.LESSONS}", file=sys.stderr)
        return 1

    routing = L.load_routing()
    all_lessons = L.parse(L.LESSONS.read_text())
    live = [l for l in all_lessons if L.live(l, routing)]
    proposed = [l["id"] for l in all_lessons if l["status"] == "proposed"]

    # 1. static CLAUDE.md blocks
    static = [l for l in live if l["severity"] in routing["inject_severities"] and not l.get("match")]
    targets, unrouted = {}, []
    for l in static:
        repos = L.target_repos(l, routing)
        if not repos:
            unrouted.append(l)
        for r in repos:
            targets.setdefault(r / "CLAUDE.md", []).append(l)

    legacy = [tuple(m) for m in routing["legacy_markers"]]
    preview = [f"# Lessons injection preview ({'APPLY' if args.apply else 'DRY-RUN'})", ""]
    wrote = 0
    for path in sorted(targets, key=str):
        block, kept, dropped = render_block(targets[path], routing["inject_token_budget"])
        status = "SKIP (no CLAUDE.md)"
        if path.exists():
            old, new = upsert(path, block, legacy)
            status = "unchanged" if old == new else ("written" if args.apply else "would-write")
            if args.apply and old != new:
                path.write_text(new)
                wrote += 1
        preview += [f"## {path} ({status}; {kept} kept, {dropped} over budget)", "", "```markdown", block.rstrip(), "```", ""]

    # Files that carried a block last run but get no lessons now: remove the stale block.
    try:
        previous = json.loads(L.MANIFEST.read_text()).get("claude_md", [])
    except Exception:
        previous = []
    for prev in previous:
        path = pathlib.Path(prev)
        if path in targets or not path.exists():
            continue
        old = path.read_text()
        new = strip_block(old, BEGIN, END)
        if new != old:
            preview += [f"## {path} (block removed: no lessons route here any more)", ""]
            if args.apply:
                path.write_text(new)
                wrote += 1

    # 2. just-in-time manifest
    jit, bad = [], []
    for l in live:
        if not l.get("match") or l["severity"] not in routing["jit_severities"]:
            continue
        try:
            alts = L.parse_match(l["match"])
        except Exception as e:  # a broken matcher must not take the whole manifest down
            bad.append(f"{l['id']}: {e}")
            continue
        dirs = [str(p) for p in L.target_repos(l, routing)]
        if not dirs:
            unrouted.append(l)
            continue
        jit.append({"id": l["id"], "severity": l["severity"], "summary": L.one_line(l),
                    "rule": l.get("rule", "").strip()[:1200], "match": alts, "dirs": dirs})
    manifest = {"vault": str(L.VAULT), "name": L.NAME, "lessons": jit, "proposed": proposed,
                "claude_md": sorted(str(p) for p in targets if p.exists())}
    body = json.dumps(manifest, ensure_ascii=False, indent=1) + "\n"
    if args.apply and (not L.MANIFEST.exists() or L.MANIFEST.read_text() != body):
        L.MANIFEST.write_text(body)

    if unrouted:
        preview += ["## Unrouted (no target repo; ledger/search only)", ""] + [f"- {l['id']} `{l.get('scope','?')}`" for l in unrouted] + [""]
    if bad:
        preview += ["## Matchers rejected", ""] + [f"- {b}" for b in bad] + [""]
    PREVIEW.write_text("\n".join(preview))
    print(f"[render-lessons] {'APPLIED' if args.apply else 'DRY-RUN'}: {len(all_lessons)} lessons, {len(live)} live, "
          f"{len(static)} static -> {len(targets)} CLAUDE.md ({wrote} written), {len(jit)} just-in-time, "
          f"{len(proposed)} proposed, {len(unrouted)} unrouted, {len(bad)} bad matchers")
    return 0


if __name__ == "__main__":
    sys.exit(main())

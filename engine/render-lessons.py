#!/usr/bin/env python3
"""Render the lessons ledger (wiki/lessons.md) into CLAUDE.md files.

Injects scope-matched lessons into a sentinel-delimited block in each target CLAUDE.md,
so every agent session reads the relevant "don't repeat this" rules at startup.

Routing (config: meta/brain.env for DEV/BRAIN_NAME, meta/lessons-routing.json for maps):
  scope: universal        -> $DEV/CLAUDE.md (parent of every repo, so loaded everywhere)
  scope: stack:<name>     -> CLAUDE.md of each repo whose repo_stacks entry lists <name>
  scope: repo:<path>      -> $DEV/<path>/CLAUDE.md
  scope: project:<slug>   -> repos in project_to_repos[slug]
  graduated: <anything>   -> excluded (became a hook/lint/test/CI guardrail)
  severity not in inject_severities -> search-only, never injected

Default is a dry run that writes meta/lessons-injection-preview.md. --apply writes.
Only writes CLAUDE.md files that already exist (never creates them).
"""
import argparse
import datetime
import json
import pathlib
import re
import sys

VAULT = pathlib.Path(__file__).resolve().parent.parent


def _env(path):
    out = {}
    if path.exists():
        for line in path.read_text().splitlines():
            m = re.match(r'^\s*([A-Z_]+)=(.*)$', line)
            if m:
                out[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    return out


ENV = _env(VAULT / "meta" / "brain.env")
DEV = pathlib.Path(ENV.get("DEV", str(pathlib.Path.home() / "Dev"))).expanduser()
NAME = ENV.get("BRAIN_NAME", "brain")
LESSONS = VAULT / "wiki" / "lessons.md"
TOP = DEV / "CLAUDE.md"
PREVIEW = VAULT / "meta" / "lessons-injection-preview.md"

# Marker carries the brain name so two brains can share a parent CLAUDE.md without
# overwriting each other's block.
BEGIN = f"<!-- BRAIN-LESSONS:{NAME} BEGIN (auto-generated by brain sync; edits between markers are overwritten) -->"
END = f"<!-- BRAIN-LESSONS:{NAME} END -->"

_routing_path = VAULT / "meta" / "lessons-routing.json"
ROUTING = json.loads(_routing_path.read_text()) if _routing_path.exists() else {}
INJECT_SEVERITIES = set(ROUTING.get("inject_severities", ["high"]))
REPO_STACKS = {k: set(v) for k, v in ROUTING.get("repo_stacks", {}).items()}
PROJECT_TO_REPOS = ROUTING.get("project_to_repos", {})

STACK_TO_REPOS = {}
for _repo, _stacks in REPO_STACKS.items():
    for _s in _stacks:
        STACK_TO_REPOS.setdefault(_s, []).append(_repo)

SEV_ORDER = {"high": 0, "med": 1, "low": 2}


def parse_lessons(text):
    lessons = []
    blocks = re.split(r"^### (L\d+.*)$", text, flags=re.M)
    # blocks = [preamble, title1, body1, title2, body2, ...]
    for i in range(1, len(blocks), 2):
        title = blocks[i].strip()
        body = blocks[i + 1]
        fields = {}
        for m in re.finditer(r"^- (\w+):\s*(.*)$", body, flags=re.M):
            fields[m.group(1)] = m.group(2).strip()
        fields["title"] = title
        lessons.append(fields)
    return lessons


def applicable(lesson):
    """Return list of target CLAUDE.md paths for this lesson (may be empty = unrouted).

    Assumes the severity gate has already been applied by the caller.
    """
    if "graduated" in lesson:
        return []
    scope = lesson.get("scope", "").strip()
    if scope == "universal":
        return [TOP]
    if scope.startswith("stack:"):
        # route only to repos that use this stack — NOT the everywhere-file
        return [DEV / r / "CLAUDE.md" for r in STACK_TO_REPOS.get(scope[len("stack:"):], [])]
    if scope.startswith("repo:"):
        return [DEV / scope[len("repo:"):] / "CLAUDE.md"]
    if scope.startswith("project:"):
        slug = scope[len("project:"):]
        if slug in PROJECT_TO_REPOS:
            return [DEV / r / "CLAUDE.md" for r in PROJECT_TO_REPOS[slug]]
        # No explicit mapping: a repo directly under DEV with the same name is the obvious target.
        return [DEV / slug / "CLAUDE.md"] if (DEV / slug / ".git").exists() else []
    return []


def render_block(lessons, today):
    lessons = sorted(
        lessons,
        key=lambda x: (SEV_ORDER.get(x.get("severity", "low"), 3), -int(x.get("hits", "1") or 1)),
    )
    # NOTE: deliberately NO render date here — the block must be byte-identical when the
    # lessons are unchanged, so it stays in the prompt cache across days/sessions.
    lines = [
        BEGIN,
        "## Lessons — do not repeat these (auto-generated; do not edit between markers)",
        f"_Auto-generated from `{VAULT.name}/wiki/lessons.md` · {len(lessons)} lesson(s)._",
        "",
    ]
    for l in lessons:
        sev = l.get("severity", "low")
        trig = re.sub(r"^[Ww]hen\s+", "", l.get("trigger", "").strip()).rstrip(".")
        rule = l.get("rule", "").rstrip(".")
        mistake = l.get("mistake", "").rstrip(".")
        lines.append(f"- **[{sev}] When {trig}:** {rule}. _(was: {mistake})_")
    lines.append(END)
    return "\n".join(lines) + "\n"


def upsert_block(path, block):
    """Return (old_text, new_text). Replace between markers, else append."""
    old = path.read_text() if path.exists() else ""
    if BEGIN in old and END in old:
        new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", block, old, flags=re.S)
    else:
        sep = "" if old.endswith("\n\n") or old == "" else ("\n" if old.endswith("\n") else "\n\n")
        new = old + sep + "\n" + block
    return old, new


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="write into CLAUDE.md files (default: dry-run preview)")
    args = ap.parse_args()

    if not LESSONS.exists():
        print(f"no lessons file at {LESSONS}", file=sys.stderr)
        return 1

    today = datetime.date.today().isoformat()
    all_lessons = parse_lessons(LESSONS.read_text())

    # severity gate: only inject the allowed severities; the rest stay search-only.
    lessons = [l for l in all_lessons if l.get("severity", "").strip() in INJECT_SEVERITIES]
    gated_out = len(all_lessons) - len(lessons)

    targets = {}   # path -> [lessons]
    unrouted = []
    for l in lessons:
        paths = applicable(l)
        if not paths:
            if "graduated" not in l:
                unrouted.append(l)
            continue
        for p in paths:
            targets.setdefault(p, []).append(l)

    preview = [f"# Lessons injection preview — {today}", "",
               f"Source: `wiki/lessons.md` ({len(lessons)} lessons). Mode: {'APPLY' if args.apply else 'DRY-RUN'}.", ""]
    wrote = 0
    for path in sorted(targets, key=str):
        block = render_block(targets[path], today)
        exists = path.exists()
        old, new = upsert_block(path, block)
        status = "would-write" if not args.apply else "written"
        if not exists:
            status = "SKIP (no CLAUDE.md)"
        elif old == new:
            status = "unchanged"
        preview += [f"## {path}  — {status} ({len(targets[path])} lesson(s))", "", "```markdown", block.rstrip(), "```", ""]
        if args.apply and exists and old != new:
            path.write_text(new)
            wrote += 1

    if unrouted:
        preview += ["## Unrouted lessons (no target CLAUDE.md — stay in ledger only)", ""]
        preview += [f"- {l['title']}  (`{l.get('scope','?')}`)" for l in unrouted]
        preview += [""]

    PREVIEW.write_text("\n".join(preview))
    print(f"[render-lessons] {'APPLIED' if args.apply else 'DRY-RUN'}: "
          f"inject-severities={sorted(INJECT_SEVERITIES)}, "
          f"{len(lessons)}/{len(all_lessons)} lessons pass gate ({gated_out} search-only), "
          f"{len(targets)} target(s), {wrote} written, {len(unrouted)} unrouted. Preview -> {PREVIEW}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
